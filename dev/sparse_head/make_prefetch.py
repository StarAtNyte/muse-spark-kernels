"""Pipeline global K prefetch and pack shared K for vector fragment loads."""
import ast,runpy
from pathlib import Path
k=runpy.run_path('dev/sparse_head/decode_kernel_tile16.py');s=k['CUDA']
s=s.replace('__launch_bounds__(128,4)','__launch_bounds__(128,1)')
marker='__device__ __forceinline__ int ko('
helpers=r'''
__device__ __forceinline__ void ldn(uint32_t* r,const void* p) {
 uint32_t a=(uint32_t)__cvta_generic_to_shared(p);
 asm volatile("ldmatrix.sync.aligned.m8n8.x4.shared.b16 {%0,%1,%2,%3},[%4];"
 :"=r"(r[0]),"=r"(r[1]),"=r"(r[2]),"=r"(r[3]):"r"(a):"memory");
}
__device__ __forceinline__ uint4 gl4(const void* p) {
 uint4 r;
 asm volatile("ld.global.cg.v4.u32 {%0,%1,%2,%3},[%4];"
 :"=r"(r.x),"=r"(r.y),"=r"(r.z),"=r"(r.w):"l"(p):"memory");
 return r;
}
'''
s=s.replace(marker,helpers+'\n'+marker,1)
s=s.replace('S*4*4096','(S+1)*4*2048')
a=s.index(' auto issue=[&](int s) {');b=s.index(' float o[8][4]',a)
new=r'''
 uint8_t* kw=mem+warp*2048;
 uint4 knext[2][2];
 auto loadK=[&](int tile) {
#pragma unroll
  for(int kg=0;kg<2;kg++) {
   int li=tile*64+warp*16+kg*8+g;
   long rr=li<n?rows[li]:0;
   knext[kg][0]=gl4(KC+rr*128+t*16);
   knext[kg][1]=gl4(KC+rr*128+64+t*16);
  }
 };
 auto storeK=[&]() {
#pragma unroll
  for(int kg=0;kg<2;kg++) {
   int key=kg*8+g;
   uint4 a=knext[kg][0],b=knext[kg][1];
   uint4 x,y;
   x.x=__byte_perm(a.x,b.x,0x5410);x.y=__byte_perm(a.x,b.x,0x7632);
   x.z=__byte_perm(a.y,b.y,0x5410);x.w=__byte_perm(a.y,b.y,0x7632);
   y.x=__byte_perm(a.z,b.z,0x5410);y.y=__byte_perm(a.z,b.z,0x7632);
   y.z=__byte_perm(a.w,b.w,0x5410);y.w=__byte_perm(a.w,b.w,0x7632);
   *reinterpret_cast<uint4*>(kw+ko(key,t*32))=x;
   *reinterpret_cast<uint4*>(kw+ko(key,t*32+16))=y;
  }
 };
 auto issueV=[&](int tile) {
  if(tile<tiles) {
   uint8_t* dst=mem+4*2048+((tile%S)*4+warp)*2048;
#pragma unroll
   for(int i=lane;i<128;i+=32) {
    int key=i>>3,c=i&7,li=tile*64+warp*16+key;
    long rr=li<n?rows[li]:0;
    int vr=(key>>1)*4+2*(c>>2)+(key&1);
    int off=vr*64+(((c&3)^(vr&3))*16);
    const uint8_t* src=VC+rr*128+c*16;
    uint32_t ad=(uint32_t)__cvta_generic_to_shared(dst+off);
    asm volatile("cp.async.cg.shared.global [%0],[%1],16;"::"r"(ad),"l"(src));
   }
  }
  asm volatile("cp.async.commit_group;");
 };
 issueV(0);
 if(tiles>0){loadK(0);storeK();}
 __syncwarp();
'''
s=s[:a]+new+s[b:]
s=s.replace('__syncwarp();issue(s+S-1);','__syncwarp();issueV(s+1);if(s+1<tiles)loadK(s+1);')
s=s.replace('const uint8_t* raw=mem+((s%S)*4+warp)*4096;\n  const uint8_t* vr=raw+2048;', 'const uint8_t* raw=kw;\n  const uint8_t* vr=mem+4*2048+((s%S)*4+warp)*2048;')
old='''    uint32_t bv[4];
#pragma unroll
    for(int j=0;j<4;j++) {
     int d=kb*32+8*j+2*t,key=nt*8+g;
     uint16_t lo=*reinterpret_cast<const uint16_t*>(raw+ko(key,d));
     uint16_t hi=*reinterpret_cast<const uint16_t*>(raw+ko(key,64+d));
     bv[j]=uint32_t(lo)|(uint32_t(hi)<<16);
    }
'''
new='''    uint32_t bv[4];
    ldn(bv,raw+ko(nt*8+(lane&7),kb*64+(lane>>3)*16));
'''
assert s.count(old)==1
s=s.replace(old,new)
old='''  __syncwarp();
 }
 asm volatile("cp.async.wait_group 0;");'''
new='''  if(s+1<tiles)storeK();
  __syncwarp();
 }
 asm volatile("cp.async.wait_group 0;");'''
assert s.count(old)==1
s=s.replace(old,new)
s=s.replace('dyn=2*4*4096','dyn=3*4*2048')
out='"""Register-prefetched packed-head sparse decode; generated by make_prefetch.py."""\nCPP='+repr(k['CPP'])+'\nCUDA='+repr(s)+'\n'
ast.parse(out)
Path('dev/sparse_head/decode_kernel_prefetch.py').write_text(out)
