"""Narrow the sparse decode tile to reduce live score/copy operands."""
import ast,runpy
from pathlib import Path
k=runpy.run_path('dev/sparse_head/decode_kernel.py')
s=k['CUDA']
replacements={
'__launch_bounds__(128,3)':'__launch_bounds__(128,4)',
'((n+31)/32-warp+3)/4':'((n+15)/16-warp+3)/4',
'S*4*8192':'S*4*4096',
'((s%S)*4+warp)*8192':'((s%S)*4+warp)*4096',
'i<512;i+=32':'i<256;i+=32',
'li=s*128+warp*32+key':'li=s*64+warp*16+key',
'off=iv?4096+':'off=iv?2048+',
'vr=raw+4096':'vr=raw+2048',
'tb=begin+s*128+warp*32':'tb=begin+s*64+warp*16',
'sv[4][4]':'sv[2][4]',
'nt<4;nt++':'nt<2;nt++',
'pa[4][2]':'pa[2][2]',
'kk<2;kk++':'kk<1;kk++',
'dyn=2*4*8192':'dyn=2*4*4096',
}
for old,new in replacements.items():
 assert old in s,old
 s=s.replace(old,new)
out='"""16-key tile variant; generated by make_tile16.py."""\nCPP='+repr(k['CPP'])+'\nCUDA='+repr(s)+'\n'
ast.parse(out)
Path('dev/sparse_head/decode_kernel_tile16.py').write_text(out)
