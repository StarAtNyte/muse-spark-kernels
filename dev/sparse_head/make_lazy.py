"""Transfer validated conditional online-softmax rescaling to packed decode."""
import ast,runpy
from pathlib import Path
k=runpy.run_path('dev/sparse_head/decode_kernel_prefetch.py');s=k['CUDA']
old='''#pragma unroll
  for(int h=0;h<2;h++) {
   mx[h]=fmaxf(mx[h],__shfl_xor_sync(0xffffffffu,mx[h],1));
   mx[h]=fmaxf(mx[h],__shfl_xor_sync(0xffffffffu,mx[h],2));
   float nm=fmaxf(mm[h],mx[h]*sc2),safe=nm==-INFINITY?0.f:nm,corr=exp2f(mm[h]-safe);
   ll[h]*=corr;mm[h]=nm;
#pragma unroll
   for(int dp=0;dp<8;dp++){o[dp][2*h]*=corr;o[dp][2*h+1]*=corr;}
  }
'''
new='''#pragma unroll
  for(int h=0;h<2;h++) {
   mx[h]=fmaxf(mx[h],__shfl_xor_sync(0xffffffffu,mx[h],1));
   mx[h]=fmaxf(mx[h],__shfl_xor_sync(0xffffffffu,mx[h],2))*sc2;
  }
  // Keep a stable reference max; update before any FP16 probability exceeds 256.
  if(__any_sync(0xffffffffu,mx[0]>mm[0]+8.f || mx[1]>mm[1]+8.f)) {
#pragma unroll
   for(int h=0;h<2;h++) {
    float nm=fmaxf(mm[h],mx[h]),safe=nm==-INFINITY?0.f:nm,corr=exp2f(mm[h]-safe);
    ll[h]*=corr;mm[h]=nm;
#pragma unroll
    for(int dp=0;dp<8;dp++){o[dp][2*h]*=corr;o[dp][2*h+1]*=corr;}
   }
  }
'''
assert s.count(old)==1
s=s.replace(old,new)
out='"""Conditional rescale variant, generated by make_lazy.py."""\nCPP='+repr(k['CPP'])+'\nCUDA='+repr(s)+'\n'
ast.parse(out)
Path('dev/sparse_head/decode_kernel_lazy.py').write_text(out)
